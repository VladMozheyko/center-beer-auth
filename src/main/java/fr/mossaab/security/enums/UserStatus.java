package fr.mossaab.security.enums;

/**
 * Статус активации аккаунта пользователя.
 */
public enum UserStatus {
    /**
     * Аккаунт создан, но код активации ещё не подтверждён.
     */
    PENDING,

    /**
     * Аккаунт успешно активирован.
     */
    ACTIVATED,

    /**
     * Аккаунт просрочен (не активирован более 24 часов), может быть удалён.
     */
    EXPIRED
}
